--!nonstrict
-- pack_winboot.lua -- build fixtures/WinBoot.lua from the staged Windows media.
-- The generated module is git-ignored (Microsoft binaries are not committed).

const fs = require("@lune/fs")
const Install = require("./install")
const Vfs = require("../core/Vfs")

const STAGED = "media/win30/staged"
const OUT = "fixtures/WinBoot.lua"

const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

local function base64(data: string): string
	local out = {}
	for index = 1, #data, 3 do
		local a, b, c = string.byte(data, index, index + 2)
		local n = (a or 0) * 65536 + (b or 0) * 256 + (c or 0)
		local encoded = ""
		for shift = 18, 0, -6 do
			const index = math.floor(n / bit32.lshift(1, shift)) % 64 + 1
			encoded ..= string.sub(ALPHABET, index, index)
		end
		out[#out + 1] = encoded
	end
	local pad = (3 - #data % 3) % 3
	local result = table.concat(out)
	if pad > 0 then
		result = string.sub(result, 1, #result - pad) .. string.rep("=", pad)
	end
	return result
end

-- wrap long base64 payloads so the generated source stays readable
local function wrap(text: string, width: number): string
	local lines = {}
	for index = 1, #text, width do
		lines[#lines + 1] = string.sub(text, index, index + width - 1)
	end
	return table.concat(lines, "\n")
end

-- Reuse the install-time INI rules so the Roblox boot and the Lune harness
-- cannot drift (shell, network.drv, real-mode [386Enh], keyboard, fonts).
local function configureSystemIni(text: string): string
	const vfs = Vfs.new()
	assert(vfs:ensureDir("C:\\WINDOWS"), "failed to create C:\\WINDOWS")
	assert(vfs:writeFile("C:\\WINDOWS\\SYSTEM.INI", text), "failed to seed SYSTEM.INI")
	Install.writeSystemIni({ vfs = vfs })
	return vfs:readFile("C:\\WINDOWS\\SYSTEM.INI") or text
end

local winCom = fs.readFile(STAGED .. "/WIN.CNF")
local kernel = fs.readFile(STAGED .. "/KERNEL.EXE")
local winIni = fs.readFile(STAGED .. "/WIN.SRC")
-- Optional demo game: when the staged media has Tetris, boot straight into it.
if fs.isFile(STAGED .. "/TETRIS.EXE") then
	winIni = Install.setWinIniRunText(winIni, "C:\\WINDOWS\\TETRIS.EXE")
end
local systemIni = configureSystemIni(fs.readFile(STAGED .. "/SYSTEM.SRC"))

-- Program groups are generated, not shipped: run the same install seed into a
-- throwaway VFS and pack the resulting PROGMAN.INI + .GRP files.
const groupVfs = Vfs.new()
Install.seed({ vfs = groupVfs })
local groupData = {}
for _, name in { "PROGMAN.INI", "MAIN.GRP", "ACCESSOR.GRP", "GAMES.GRP" } do
	groupData[name] = assert(groupVfs:readFile("C:\\WINDOWS\\" .. name), "missing group " .. name)
end

local source = table.concat({
	"--!nonstrict",
	"-- generated by tools/pack_winboot.lua -- DO NOT COMMIT (Microsoft binaries)",
	"local A2B = {}",
	'local CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"',
	"for i = 1, #CHARS do",
	"\tA2B[string.sub(CHARS, i, i)] = i - 1",
	"end",
	"local function decode(s)",
	'\ts = string.gsub(s, "%s+", ""):gsub("=", "")',
	"\tlocal out = {}",
	"\tlocal acc, count = 0, 0",
	"\tfor i = 1, #s do",
	"\t\tacc = acc * 64 + A2B[string.sub(s, i, i)]",
	"\t\tcount += 1",
	"\t\tif count == 4 then",
	"\t\t\tout[#out + 1] = string.char(bit32.band(bit32.rshift(acc, 16), 255), bit32.band(bit32.rshift(acc, 8), 255), bit32.band(acc, 255))",
	"\t\t\tacc, count = 0, 0",
	"\t\tend",
	"\tend",
	"\tif count == 2 then",
	"\t\tout[#out + 1] = string.char(bit32.band(bit32.rshift(acc, 4), 255))",
	"\telseif count == 3 then",
	"\t\tout[#out + 1] = string.char(bit32.band(bit32.rshift(acc, 10), 255), bit32.band(bit32.rshift(acc, 2), 255))",
	"\tend",
	"\treturn table.concat(out)",
	"end",
	"return {",
	"\tdecode = decode,",
	("\twinCom = decode([[\n%s\n]]),"):format(wrap(base64(winCom), 100)),
	("\tkernel = decode([[\n%s\n]]),"):format(wrap(base64(kernel), 100)),
	("\twinIni = decode([[\n%s\n]]),"):format(wrap(base64(winIni), 100)),
	("\tsystemIni = decode([[\n%s\n]]),"):format(wrap(base64(systemIni), 100)),
	"}",
	"",
}, "\n")

fs.writeFile(OUT, source)
print(("wrote %s (%d bytes; win.com %d, kernel %d)"):format(OUT, #source, #winCom, #kernel))

local function emitFiles(path: string, names: { string })
	local parts = {
		"--!nonstrict",
		"-- generated by tools/pack_winboot.lua -- DO NOT COMMIT (Microsoft binaries)",
		"return {",
	}
	for _, name in names do
		const data = fs.readFile(STAGED .. "/" .. name)
		parts[#parts + 1] = ("\t[%q] = [[\n%s\n]],"):format(name, wrap(base64(data), 100))
	end
	parts[#parts + 1] = "}"
	parts[#parts + 1] = ""
	fs.writeFile(path, table.concat(parts, "\n"))
	print(("wrote %s (%d bytes)"):format(path, #table.concat(parts, "\n")))
end

local function emitDataFiles(path: string, files: { [string]: string })
	const parts = {
		"--!nonstrict",
		"-- generated by tools/pack_winboot.lua -- DO NOT COMMIT (Microsoft binaries)",
		"return {",
	}
	for _, name in { "PROGMAN.INI", "MAIN.GRP", "ACCESSOR.GRP", "GAMES.GRP" } do
		parts[#parts + 1] = ("\t[%q] = [[\n%s\n]],"):format(name, wrap(base64(files[name]), 100))
	end
	parts[#parts + 1] = "}"
	parts[#parts + 1] = ""
	fs.writeFile(path, table.concat(parts, "\n"))
	print(("wrote %s (%d bytes)"):format(path, #table.concat(parts, "\n")))
end

