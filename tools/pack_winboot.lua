-- large NE modules: split into base64 chunks so each ModuleScript stays well
-- below Roblox's source-size limit. Chunk sizes are multiples of 3, so the
-- base64 pieces concatenate without padding.
local function emitChunks(prefix: string, data: string): { string }
	const chunkBytes = 90_000
	const names = {}
	for index = 1, #data, chunkBytes do
		const chunk = string.sub(data, index, index + chunkBytes - 1)
		const name = prefix .. string.format("%02d", #names + 1)
		fs.writeFile(
			"fixtures/" .. name .. ".lua",
			("return [[\n%s\n]]\n"):format(wrap(base64(chunk), 100))
		)
		names[#names + 1] = name
	end
	return names
end

