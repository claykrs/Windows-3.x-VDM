-- The media ships WINVER without an extension; the guest expects WINVER.EXE.
const APP_SOURCES: { [string]: string } = {
	["WINVER.EXE"] = "WINVER",
}

local appChunkIndex = 0
local function emitAppChunks(data: string): { string }
	const chunkBytes = 90_000
	const names = {}
	for index = 1, #data, chunkBytes do
		appChunkIndex += 1
		const name = ("WinBootApp%02d"):format(appChunkIndex)
		fs.writeFile(
			"fixtures/" .. name .. ".lua",
			("return [[\n%s\n]]\n"):format(
				wrap(base64(string.sub(data, index, index + chunkBytes - 1)), 100)
			)
		)
		names[#names + 1] = name
	end
	return names
end

const big = {
	GDI = emitChunks("WinBootGDI", fs.readFile(STAGED .. "/GDI.EXE")),
	USER = emitChunks("WinBootUSER", fs.readFile(STAGED .. "/USER.EXE")),
}
local appManifest: { [string]: { string } } = {}
for _, name in APP_FILES do
	appManifest[name] = emitAppChunks(fs.readFile(STAGED .. "/" .. (APP_SOURCES[name] or name)))
end
local manifest = {
	"--!nonstrict",
	"-- generated by tools/pack_winboot.lua -- DO NOT COMMIT (Microsoft binaries)",
	"return {",
	'\t["GDI.EXE"] = {',
}
for _, name in big.GDI do
	manifest[#manifest + 1] = ("\t\t%q,"):format(name)
end
manifest[#manifest + 1] = "\t},"
manifest[#manifest + 1] = '\t["USER.EXE"] = {'
for _, name in big.USER do
	manifest[#manifest + 1] = ("\t\t%q,"):format(name)
end
manifest[#manifest + 1] = "\t},"
for _, name in APP_FILES do
	manifest[#manifest + 1] = ("\t[%q] = {"):format(name)
	for _, chunk in appManifest[name] do
		manifest[#manifest + 1] = ("\t\t%q,"):format(chunk)
	end
	manifest[#manifest + 1] = "\t},"
end
manifest[#manifest + 1] = "}"
manifest[#manifest + 1] = ""
fs.writeFile("fixtures/WinBootBig.lua", table.concat(manifest, "\n"))
print(("wrote fixtures/WinBootBig.lua (%d GDI chunks, %d USER chunks)"):format(#big.GDI, #big.USER))
